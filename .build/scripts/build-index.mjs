// 제외 규칙은 common.mjs로 일원화 (build-search-corpus.mjs와 공유).
// 산출물(*_META.md 등)·충돌 사본(*_Conflict.*)은 isSkippedFile이 걸러낸다.
async function walk(dir, common) {
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  const files = [];
  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;
    if (common.SKIP_DIRS.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(full, common)));
    } else if (entry.name.endsWith('.md') && !common.isSkippedFile(entry.name)) {
      files.push(full);
    }
  }
  return files;
}

async function findMatchingDirs(vaultRoot, pattern) {
  const entries = await fs.readdir(vaultRoot, { withFileTypes: true });
  return entries
    .filter((e) => e.isDirectory() && pattern.test(e.name))
    .map((e) => e.name)
    .sort();
}

async function isDir(p) {
  try {
    return (await fs.stat(p)).isDirectory();
  } catch {
    return false;
  }
}

