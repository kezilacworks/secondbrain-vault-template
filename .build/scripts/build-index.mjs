/**
 * vault → { locale, outputs: Map<파일명, 본문>, summaries: string[] }. 사용자 노트는 읽기만 한다.
 * opts.matter / opts.common: 주입용(시험). 없으면 형제 common.mjs와 gray-matter를 불러온다.
 */
export async function buildIndex({ vaultRoot, ...opts }) {
  const common = opts.common ?? (await import('./common.mjs'));
  const matter = opts.matter ?? (await import('gray-matter')).default;

  // 1) 설정별 파일 목록 + 원문 한 번 읽기(WORKS·MATERIAL_WIKI가 같은 폴더를 본다)
  const plan = [];
  const raws = new Map(); // 절대경로 → NFC 원문 | null(읽기 실패)
  const voters = new Set(); // 로케일 투표에 드는 노트 — 등재 조건이 있는 DB 폴더만(Inbox 제외)
  for (const c of META_CONFIGS) {
    const matchedDirs = await findMatchingDirs(vaultRoot, c.dirsPattern);
    const files = [];
    for (const dir of matchedDirs) files.push(...(await walk(path.join(vaultRoot, dir), common)));
    plan.push({ matchedDirs, files });
    if (c.output !== 'INBOX_META.md') for (const f of files) voters.add(f);
    for (const f of files) {
      if (raws.has(f)) continue;
      try {
        // NFC 정규화 후 파싱 — NFD 레거시 노트의 키·값도 META/INDEX에 NFC로 실린다.
        raws.set(f, (await fs.readFile(f, 'utf-8')).normalize('NFC'));
      } catch {
        raws.set(f, null);
      }
    }
  }

  // 2) 로케일 — 노트 frontmatter 키로 정한다
  const counts = { ko: 0, en: 0, koFolder: false, enFolder: false };
  for (const f of voters) {
    const raw = raws.get(f);
    const s = raw == null ? null : noteLocaleSignal(raw);
    if (s === 'ko' || s === 'both') counts.ko++;
    if (s === 'en' || s === 'both') counts.en++;
  }
  if (counts.ko === 0 && counts.en === 0) {
    for (const f of LOCALE_SIGNAL_FOLDERS.ko) if (await isDir(path.join(vaultRoot, f))) counts.koFolder = true;
    for (const f of LOCALE_SIGNAL_FOLDERS.en) if (await isDir(path.join(vaultRoot, f))) counts.enFolder = true;
  }
  const locale = detectLocale(counts);
  const configs = resolveConfigs(locale, await readSchemaExt(vaultRoot));

  // 3) 설정별 등재·렌더
  const outputs = new Map();
  const summaries = [];
  for (let i = 0; i < configs.length; i++) {
    const config = configs[i];
    const { matchedDirs, files } = plan[i];
    const rows = [];
    let parseFail = 0;
    for (const file of files) {
      let fm;
      try {
        const raw = raws.get(file);
        if (raw === null) throw new Error('read');
        fm = matter(raw).data;
      } catch {
        parseFail++;
        // 어떤 노트가 깨졌는지 Actions 로그에서 바로 보이게 경로를 남긴다.
        console.warn(`⚠️ frontmatter 파싱 실패: ${path.relative(vaultRoot, file)}`);
        continue;
      }
      const relPath = path.relative(vaultRoot, file).normalize('NFC');
      // filter는 (frontmatter, 상대경로) — 경로 기반 제외(템플릿 폴더 등)가 필요한 DB만 두 번째 인자 사용
      if (!fm || !config.filter(fm, relPath)) continue;
      const title = path.basename(file, '.md').normalize('NFC');
      rows.push({ title, path: relPath, fm });
    }

    rows.sort((a, b) => a.title.localeCompare(b.title, 'ko'));

    // 1) .md: render가 있으면 커스텀(그룹) 렌더, 없으면 기본 큐레이션 테이블
    const ctx = { rows, matchedDirs, parseFail, columns: config.columns };
    outputs.set(config.output, typeof config.render === 'function' ? config.render(ctx) : renderTable(config, ctx, locale));

    // 2) 전체 프론트매터 JSON 사이드카 (기계용). 건강 확인 도장은 STAMP_OUTPUT 한 곳에만 싣는다.
    const jsonDoc = {
      db: config.output.replace('_META.md', ''),
      ...(config.json === STAMP_OUTPUT ? { generator_version: GENERATOR_VERSION } : {}),
      generated_at: new Date().toISOString(),
      matched_dirs: matchedDirs,
      count: rows.length,
      items: rows.map((r) => ({
        title: r.title,
        path: r.path,
        frontmatter: normalizeFm(r.fm),
      })),
    };
    outputs.set(config.json, JSON.stringify(jsonDoc, null, 2) + '\n');

    summaries.push(
      `✅ ${config.output} + ${config.json}: ${rows.length} entries (matched dirs: ${matchedDirs.join(', ') || 'none'})${parseFail ? ` (skipped ${parseFail} parse failures)` : ''}`,
    );
  }
  return { locale, outputs, summaries };
}

function defaultVaultRoot() {
  // vault 루트 = 이 스크립트(.build/scripts/) 기준 두 단계 상위. cwd와 무관하게 동작하므로
  // 어디서 호출하든(루트 / .build / Actions working-directory) 산출물이 항상 vault 루트로 간다.
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
}

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--vault') out.vault = argv[++i];
    else if (argv[i] === '--out-dir') out.outDir = argv[++i];
  }
  return out;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const vaultRoot = path.resolve(args.vault ?? defaultVaultRoot());
  const outDir = path.resolve(args.outDir ?? vaultRoot);
  const { locale, outputs, summaries } = await buildIndex({ vaultRoot });
  for (const [name, content] of outputs) await fs.writeFile(path.join(outDir, name), content);
  console.log(`build-index ${GENERATOR_VERSION} (locale ${locale})`);
  for (const line of summaries) console.log(line);
}

function isMain() {
  try {
    return Boolean(process.argv[1]) && pathToFileURL(realpathSync(process.argv[1])).href === import.meta.url;
  } catch {
    return false;
  }
}

