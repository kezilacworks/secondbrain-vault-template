const FM_BLOCK_RE = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/;
const signalRe = (keys) => new RegExp(`^(?:${keys.join('|')})[ \\t]*:`, 'm');
const SIGNAL_RE = { ko: signalRe(LOCALE_SIGNAL_KEYS.ko), en: signalRe(LOCALE_SIGNAL_KEYS.en) };

/** 노트 원문(NFC) → 'ko' | 'en' | 'both' | null. YAML을 해석하지 않고 frontmatter 블록의 줄머리 키만 본다. */
export function noteLocaleSignal(raw) {
  const m = FM_BLOCK_RE.exec(raw);
  if (!m) return null;
  const ko = SIGNAL_RE.ko.test(m[1]);
  const en = SIGNAL_RE.en.test(m[1]);
  return ko && en ? 'both' : ko ? 'ko' : en ? 'en' : null;
}

/**
 * 목차 언어 — build-journal-index.mjs detectLocale과 같은 규칙: 신호 노트가 많은 쪽, 같으면 ko. 신호 노트가
 * 하나도 없으면 KO 종류 폴더만 있을 때 ko, 그 밖은 en(신규 가입자 기본 로케일) — 노트가 생기는 첫 push에 바로 따라간다.
 */
export function detectLocale(counts) {
  const ko = counts.ko ?? 0;
  const en = counts.en ?? 0;
  if (ko === 0 && en === 0) return counts.koFolder && !counts.enFolder ? 'ko' : 'en';
  return ko >= en ? 'ko' : 'en';
}

