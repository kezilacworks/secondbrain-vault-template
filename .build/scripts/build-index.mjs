export function formatCell(value) {
  if (value == null || value === '') return '';
  if (value instanceof Date) return isoDate(value);
  if (Array.isArray(value)) {
    return value.filter((v) => v != null && v !== '').join(', ').replace(/\|/g, '\\|');
  }
  return String(value).replace(/\|/g, '\\|').replace(/\n/g, ' ').trim();
}

/** Date → 'YYYY-MM-DD' (시각 정보 손실 OK; 노트 날짜는 day 단위). */
function isoDate(d) {
  if (!(d instanceof Date) || Number.isNaN(d.getTime())) return '';
  return d.toISOString().slice(0, 10);
}

/**
 * 프론트매터를 JSON 직렬화 가능 형태로 정규화.
 * - Date → 'YYYY-MM-DD' (gray-matter가 YAML date를 Date로 파싱 → ISO보다 day 포맷이 정렬·표시 모두 깔끔)
 * - 배열/원시값은 그대로. 중첩 객체는 재귀.
 */
function normalizeFm(fm) {
  const out = {};
  for (const [k, v] of Object.entries(fm)) {
    out[k] = normalizeValue(v);
  }
  return out;
}

function normalizeValue(v) {
  if (v instanceof Date) return isoDate(v);
  if (Array.isArray(v)) return v.map(normalizeValue);
  if (v && typeof v === 'object') return normalizeFm(v);
  return v;
}

/** rows를 frontmatter 필드값으로 묶어 "- {키} (n): [[a]], [[b]]" 줄 생성 (KNOWHOW 그룹 렌더용) */
function groupSection(rows, field, locale) {
  const groups = new Map();
  for (const r of rows) {
    const key = r.fm[field];
    if (key == null || key === '') continue;
    const k = String(key);
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(r.title);
  }
  if (groups.size === 0) return `- (${TEXT[locale].none})`;
  return [...groups.keys()]
    .sort((a, b) => a.localeCompare(b, 'ko'))
    .map((k) => {
      const titles = groups.get(k).sort((a, b) => a.localeCompare(b, 'ko'));
      return `- ${k} (${titles.length}): ${titles.map((t) => `[[${t}]]`).join(', ')}`;
    })
    .join('\n');
}

/** Inbox 표 — frontmatter 제목(title) 우선, 없으면 파일명 폴백(실측 절반이 제목을 안 채운다). wikilink는 만들지 않는다. */
function renderInbox({ rows, columns }, locale, preamble) {
  const titleKey = locale === 'ko' ? '제목' : 'title';
  const header = `| ${TEXT[locale].title} | ${columns.join(' | ')} |`;
  const sep = `| --- | ${columns.map(() => '---').join(' | ')} |`;
  const body = rows.map((r) => {
    const displayTitle = formatCell(r.fm[titleKey]) || r.title;
    const cells = columns.map((c) => formatCell(r.fm[c]));
    return `| ${String(displayTitle).replace(/\|/g, '\\|')} | ${cells.join(' | ')} |`;
  });
  return ['# INBOX_META', '', ...preamble, '', header, sep, ...body, '', '---', TEXT[locale].footer, ''].join('\n');
}

function renderTable(config, { rows, matchedDirs, parseFail }, locale) {
  const t = TEXT[locale];
  const header = `| ${t.title} | ${config.columns.join(' | ')} |`;
  const sep = `| --- | ${config.columns.map(() => '---').join(' | ')} |`;
  const body = rows.map((r) => {
    const cells = config.columns.map((c) => formatCell(r.fm[c]));
    const safeTitle = String(r.title).replace(/\|/g, '\\|');
    return `| [[${safeTitle}]] | ${cells.join(' | ')} |`;
  });
  return [
    `# ${config.output.replace('.md', '')}`,
    '',
    t.tableNote,
    `${t.updated}${new Date().toISOString()}`,
    `${t.matched}${matchedDirs.join(', ') || `(${t.none})`}`,
    `${t.count}${rows.length}${parseFail ? ` (${t.parseFail}: ${parseFail})` : ''}`,
    '',
    header,
    sep,
    ...body,
    '',
    '---',
    t.footer,
    '',
  ].join('\n');
}

